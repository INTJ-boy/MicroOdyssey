function getLang(){ return localStorage.getItem("mo_lang") || "en"; }
function applyLang(lang){
  document.documentElement.lang = lang;
  document.documentElement.dir = I18N[lang].dir;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(I18N[lang][key] !== undefined) el.textContent = I18N[lang][key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el=>{
    const key = el.getAttribute("data-i18n-ph");
    if(I18N[lang][key] !== undefined) el.setAttribute("placeholder", I18N[lang][key]);
  });
  document.querySelectorAll(".lang-options button").forEach(b=>{
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  document.querySelectorAll(".cur-lang").forEach(el=>{
    el.textContent = lang.toUpperCase();
  });
  window.__mo_lang = lang;
}
function initLangToggle(){
  const lang = getLang();
  document.querySelectorAll(".lang-switch").forEach(sw=>{
    const trigger = sw.querySelector(".lang-trigger");
    if(!trigger) return;
    trigger.addEventListener("click", (e)=>{
      e.stopPropagation();
      const willOpen = !sw.classList.contains("open");
      document.querySelectorAll(".lang-switch.open, .nav-dropdown.open").forEach(o=>{
        o.classList.remove("open");
        const t = o.querySelector(".lang-trigger, .nav-drop-trigger");
        if(t) t.setAttribute("aria-expanded", "false");
      });
      if(willOpen){
        sw.classList.add("open");
        trigger.setAttribute("aria-expanded", "true");
      }
    });
    sw.querySelectorAll(".lang-options button").forEach(btn=>{
      btn.addEventListener("click", (e)=>{
        e.stopPropagation();
        localStorage.setItem("mo_lang", btn.dataset.lang);
        applyLang(btn.dataset.lang);
        sw.classList.remove("open");
        trigger.setAttribute("aria-expanded", "false");
        if(window.onLangChange) window.onLangChange();
      });
    });
  });
  document.addEventListener("click", ()=>{
    document.querySelectorAll(".lang-switch.open").forEach(sw=>{
      sw.classList.remove("open");
      const t = sw.querySelector(".lang-trigger");
      if(t) t.setAttribute("aria-expanded", "false");
    });
  });
  applyLang(lang);
}
